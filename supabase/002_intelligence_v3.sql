create index if not exists btc_prediction_market_market_idx on public.btc_prediction_market_snapshots(provider, market_id, observed_at desc);

create table if not exists public.btc_news_events (
  id bigint generated by default as identity primary key,
  observed_at timestamptz not null default now(),
  published_at timestamptz,
  source text not null,
  source_tier smallint not null default 1,
  headline text not null,
