  skew jsonb not null default '{}'::jsonb,
  expiries jsonb not null default '[]'::jsonb,
  strikes jsonb not null default '[]'::jsonb,
  gamma_context jsonb not null default '{}'::jsonb,
  max_pain jsonb not null default '{}'::jsonb,
  data_status text not null default 'LIVE' check (data_status in ('LIVE','DELAYED','ESTIMATED','PRELIMINARY','FINAL','STALE','PARTIAL','UNAVAILABLE')),
