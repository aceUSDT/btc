create or replace function private.btc_prune_v3_history()
returns void
language plpgsql
security definer
set search_path = pg_catalog
as $$
begin
  delete from public.btc_feature_snapshots where observed_at < now() - interval '365 days';
  delete from public.btc_options_snapshots where observed_at < now() - interval '365 days';
  delete from public.btc_prediction_market_snapshots where observed_at < now() - interval '180 days';
  delete from public.btc_cross_asset_snapshots where observed_at < now() - interval '365 days';
  delete from public.btc_onchain_snapshots where observed_at < now() - interval '730 days';
end;
$$;
revoke all on function private.btc_prune_v3_history() from public;
revoke all on function private.btc_prune_v3_history() from anon, authenticated;
grant execute on function private.btc_prune_v3_history() to service_role;
