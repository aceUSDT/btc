-- BTC Global Intelligence v3 durable feature store.
-- Railway is the single authoritative compute/ingestion engine; Supabase is
-- durable state, configuration and audit history only.

create table if not exists public.btc_feature_snapshots (
  id bigint generated by default as identity primary key,
  observed_at timestamptz not null default now(),
  engine_version text not null,
  price_usd numeric,
  structure jsonb not null default '{}'::jsonb,
  external jsonb not null default '{}'::jsonb,
  signal jsonb not null default '{}'::jsonb,
  coverage jsonb not null default '{}'::jsonb
);
create index if not exists btc_feature_snapshots_observed_idx on public.btc_feature_snapshots(observed_at desc);

create table if not exists public.btc_macro_events (
  id bigint generated by default as identity primary key,
  event_key text not null,
  scheduled_at timestamptz,
  released_at timestamptz,
  event_name text not null,
  source text not null,
  status text not null default 'SCHEDULED' check (status in ('SCHEDULED','LIVE','PRELIMINARY','FINAL','REVISED','CANCELLED','UNAVAILABLE')),
  actual numeric,
  consensus numeric,
  previous numeric,
  revision numeric,
  surprise numeric,
  units text,
  importance text check (importance in ('LOW','MEDIUM','HIGH','CRITICAL')),
  btc_pre_context jsonb not null default '{}'::jsonb,
  btc_post_reaction jsonb not null default '{}'::jsonb,
  raw jsonb not null default '{}'::jsonb,
  updated_at timestamptz not null default now()
);
create unique index if not exists btc_macro_events_key_idx on public.btc_macro_events(event_key);
create index if not exists btc_macro_events_time_idx on public.btc_macro_events(scheduled_at desc);

