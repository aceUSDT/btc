create table if not exists public.btc_liquidation_clusters (
  id bigint generated by default as identity primary key,
  observed_at timestamptz not null default now(),
  horizon text not null,
  side text not null check (side in ('above','below')),
  price_usd numeric not null,
  estimated_notional_usd numeric,
  distance_pct numeric,
  provider text not null,
  data_status text not null default 'ESTIMATED' check (data_status in ('LIVE','DELAYED','ESTIMATED','PRELIMINARY','FINAL','STALE','PARTIAL','UNAVAILABLE')),
