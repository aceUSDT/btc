create or replace view public.btc_latest_state as
select * from public.btc_market_snapshots order by observed_at desc limit 1;

create or replace view public.btc_current_intelligence as
select m.*, s.primary_regime, s.secondary_regime, s.regime_confidence, s.bull_score, s.bear_score,
       s.trade_confidence, s.event_risk, s.preferred_action, s.active_setup, s.watchlist, s.explainability
from public.btc_latest_state m
cross join public.btc_signal_state s
where s.singleton = true;

create or replace function private.btc_prune_history()
returns void
language plpgsql
security definer
set search_path = pg_catalog
as $$
begin
  delete from public.btc_exchange_snapshots where observed_at < now() - interval '30 days';
  delete from public.btc_market_snapshots where observed_at < now() - interval '180 days';
  delete from public.btc_liquidation_clusters where observed_at < now() - interval '30 days';
end;
$$;
revoke all on function private.btc_prune_history() from public;
revoke all on function private.btc_prune_history() from anon, authenticated;
grant execute on function private.btc_prune_history() to service_role;

