create index if not exists btc_liq_clusters_obs_idx on public.btc_liquidation_clusters (observed_at desc, horizon, side);

create table if not exists public.btc_signal_state (
  singleton boolean primary key default true check (singleton),
  updated_at timestamptz not null default now(),
  primary_regime text,
  secondary_regime text,
  regime_confidence numeric check (regime_confidence between 0 and 100),
  bull_score numeric check (bull_score between 0 and 100),
  bear_score numeric check (bear_score between 0 and 100),
  trade_confidence numeric check (trade_confidence between 0 and 100),
  event_risk text check (event_risk in ('LOW','MEDIUM','HIGH','EXTREME')),
  preferred_action text,
  active_setup jsonb not null default '{}'::jsonb,
  watchlist jsonb not null default '[]'::jsonb,
  explainability jsonb not null default '{}'::jsonb
);
insert into public.btc_signal_state(singleton) values (true) on conflict (singleton) do nothing;

