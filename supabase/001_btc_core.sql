create schema if not exists private;
revoke all on schema private from public;
revoke all on schema private from anon, authenticated;

create table if not exists public.btc_data_sources (
  source_key text primary key,
  category text not null,
  display_name text not null,
  base_url text,
  priority integer not null default 100,
  enabled boolean not null default true,
  expected_mode text not null default 'REST',
  notes text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.btc_exchange_snapshots (
  id bigint generated by default as identity primary key,
  observed_at timestamptz not null default now(),
  source_key text references public.btc_data_sources(source_key),
  venue text not null,
  market_type text not null check (market_type in ('spot','perp','futures','options','index')),
  symbol text not null,
  price_usd numeric,
  bid_usd numeric,
  ask_usd numeric,
  spread_bps numeric,
  volume_usd_24h numeric,
  open_interest_usd numeric,
  funding_rate numeric,
  funding_interval_hours numeric,
  taker_buy_usd_1m numeric,
  taker_sell_usd_1m numeric,
  cvd_usd_1m numeric,
  sample_trade_count integer,
  sample_coverage_ms integer,
  data_status text not null default 'LIVE' check (data_status in ('LIVE','DELAYED','ESTIMATED','PRELIMINARY','FINAL','STALE','PARTIAL','UNAVAILABLE')),
  source_event_at timestamptz,
  received_at timestamptz not null default now(),
  latency_ms integer,
  sequence_ok boolean,
  quality_score numeric check (quality_score between 0 and 100),
  raw jsonb not null default '{}'::jsonb
);
create index if not exists btc_exchange_snapshots_observed_idx on public.btc_exchange_snapshots (observed_at desc);
create index if not exists btc_exchange_snapshots_venue_market_idx on public.btc_exchange_snapshots (venue, market_type, observed_at desc);

