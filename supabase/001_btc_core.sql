  status text not null default 'WATCH' check (status in ('WATCH','TRIGGERED','INVALIDATED','EXPIRED','CLOSED')),
  setup_type text not null,
  direction text not null check (direction in ('LONG','SHORT','NEUTRAL')),
  time_horizon text,
  confidence numeric check (confidence between 0 and 100),
  data_quality numeric check (data_quality between 0 and 100),
  entry_zone jsonb,
  trigger_required text,
  invalidation text,
  stop_risk_level numeric,
  targets jsonb,
  expected_rr numeric,
  key_levels jsonb,
  evidence jsonb not null default '{}'::jsonb,
  contradictions jsonb not null default '[]'::jsonb,
  cancel_conditions jsonb not null default '[]'::jsonb,
  expires_at timestamptz,
  outcome jsonb,
  updated_at timestamptz not null default now()
);
create index if not exists btc_setups_status_idx on public.btc_setups (status, detected_at desc);

create table if not exists public.btc_alerts (
  id bigint generated by default as identity primary key,
  created_at timestamptz not null default now(),
  priority text not null check (priority in ('INFO','WATCH','HIGH','CRITICAL')),
  alert_type text not null,
  dedupe_key text,
  title text not null,
  payload jsonb not null,
  delivered_channels jsonb not null default '[]'::jsonb,
  delivered_at timestamptz
);
create unique index if not exists btc_alerts_dedupe_idx on public.btc_alerts (dedupe_key) where dedupe_key is not null;

